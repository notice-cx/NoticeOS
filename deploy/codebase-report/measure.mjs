const ASSET = /^[A-Za-z0-9][A-Za-z0-9._:-]{0,252}$/u;
const REF = /^[A-Za-z0-9._/@+-]{1,255}$/u;
const IMAGE_DIGEST = /^[a-z0-9][a-z0-9._/:-]{0,255}@sha256:[a-f0-9]{64}$/u;
const HELP = 'Usage: measure.mjs --asset <id> [--repo /repo] [--paths a,b] [--ref <name>] [--out <file>] [--post <ingest url>]';

/** A repository-relative path, normalized to forward slashes, or null when it could leave the repository. */
export function safeRelativePath(value) {
  if (typeof value !== 'string' || value.length === 0 || value.length > LIMITS.pathChars) return null;
  if (/[\0\r\n\\]/u.test(value) || value.startsWith('/') || /^[A-Za-z]:/u.test(value)) return null;
  const parts = value.split('/').filter((part) => part !== '' && part !== '.');
  if (parts.length === 0 || parts.some((part) => part === '..')) return null;
  return parts.join('/');
}

export function parseArgs(argv) {
  const known = new Set(['--asset', '--repo', '--paths', '--ref', '--out', '--post']);
  const values = {};
  for (let i = 0; i < argv.length; i += 1) {
    const flag = argv[i];
    if (flag === '--') continue;
    if (!known.has(flag) || flag in values) throw new Error(HELP);
    const value = argv[i + 1];
    if (value === undefined || value.startsWith('--')) throw new Error(`${flag} needs a value.\n${HELP}`);
    values[flag] = value;
    i += 1;
  }
  if (!values['--asset'] || !ASSET.test(values['--asset'])) throw new Error(`--asset needs the site's id, such as example.com.\n${HELP}`);
  let paths = null;
  if (values['--paths'] !== undefined) {
    const raw = values['--paths'].split(',').map((part) => part.trim()).filter(Boolean);
    paths = [...new Set(raw.map((part) => {
      const safe = safeRelativePath(part);
      if (!safe) throw new Error(`--paths takes folders inside the repository, such as apps/site; ${JSON.stringify(part)} is not one.`);
      return safe;
    }))];
    if (paths.length === 0 || paths.length > LIMITS.paths) throw new Error(`--paths takes 1 to ${LIMITS.paths} folders.`);
  }
  if (values['--ref'] !== undefined && !REF.test(values['--ref'])) throw new Error('--ref takes a branch or tag name.');
  return {
    asset: values['--asset'],
    repo: path.resolve(values['--repo'] ?? '/repo'),
    paths,
    ref: values['--ref'] ?? null,
    out: values['--out'] ? path.resolve(values['--out']) : null,
    post: values['--post'] ? ingestEndpoint(values['--post']) : null,
  };
}

/**
 * Where the report is sent: the ingest's codebase route. Plain http is
 * accepted only on this machine's loopback, so a token never crosses a
 * network unencrypted.
 */
export function ingestEndpoint(value) {
  let url;
  try { url = new URL(value); } catch { throw new Error('--post takes the ingest address, such as https://ingest.example.com.'); }
  const loopback = ['localhost', '127.0.0.1', '[::1]'].includes(url.hostname);
  if (url.protocol !== 'https:' && !(url.protocol === 'http:' && loopback)) {
    throw new Error('--post needs an https address; plain http is accepted only for localhost.');
  }
  if (url.username || url.password || url.search || url.hash) throw new Error('--post takes an address without credentials, query or fragment.');
  const base = url.pathname.replace(/\/+$/u, '');
  url.pathname = base.endsWith('/api/codebase-report') ? base : `${base}/api/codebase-report`;
  return url.toString();
}

const GLOB_SPECIAL = /[.+^$()|[\]\\]/gu;

/**
 * A glob from `.noticeos-codebase.json` as a test on a repository-relative
 * path. `*` stays inside one folder, `**` crosses folders, `{a,b}` is either.
 * A pattern without a slash matches a file or folder name anywhere; one with
 * a slash is anchored at the repository root; either matches everything
 * under a folder it names.
 */
export function globMatcher(pattern) {
  let source = pattern.trim().replace(/^\.\//u, '');
  const anchored = source.replace(/\/+$/u, '').includes('/');
  source = source.replace(/^\/+/u, '').replace(/\/+$/u, '');
  let out = '';
  for (let i = 0; i < source.length; i += 1) {
    const char = source[i];
    if (char === '*' && source[i + 1] === '*') {
      if (source[i + 2] === '/') { out += '(?:.*/)?'; i += 2; } else { out += '.*'; i += 1; }
    } else if (char === '*') out += '[^/]*';
    else if (char === '?') out += '[^/]';
    else if (char === '{') {
      const close = source.indexOf('}', i);
      if (close === -1) { out += '\\{'; continue; }
      out += `(?:${source.slice(i + 1, close).split(',').map((part) => part.replace(GLOB_SPECIAL, '\\$&').replace(/\*/gu, '[^/]*')).join('|')})`;
      i = close;
    } else out += char.replace(GLOB_SPECIAL, '\\$&');
  }
  const regex = new RegExp(`${anchored ? '^' : '(?:^|/)'}${out}(?:/.*)?$`, 'u');
  return (file) => regex.test(file);
}

/** The repository's own `.noticeos-codebase.json`, checked; a mistake in it stops the run rather than changing the numbers unseen. */
export function readRepoConfig(text) {
  if (text === null) return { exclude: [], tests: [] };
  let value;
  try { value = JSON.parse(text); } catch { throw new Error('.noticeos-codebase.json is not valid JSON.'); }
  if (!value || typeof value !== 'object' || Array.isArray(value)) throw new Error('.noticeos-codebase.json must hold one object.');
  for (const key of Object.keys(value)) {
    if (key !== 'exclude' && key !== 'tests') throw new Error(`.noticeos-codebase.json has "${key}"; it takes "exclude" and "tests" only.`);
  }
  const list = (key) => {
    const items = value[key] ?? [];
    if (!Array.isArray(items) || items.length > 200 || items.some((item) => typeof item !== 'string' || item.trim() === '' || item.length > 256)) {
      throw new Error(`.noticeos-codebase.json "${key}" must be a list of up to 200 path patterns.`);
    }
    return items;
  };
  return { exclude: list('exclude'), tests: list('tests') };
}

