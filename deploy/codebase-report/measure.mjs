const extensionOf = (file) => {
  const base = file.slice(file.lastIndexOf('/') + 1);
  const dot = base.lastIndexOf('.');
  return dot > 0 ? base.slice(dot + 1).toLowerCase() : '';
};

/** Rules a path alone decides: the default exclusions, the repository's own, and the test patterns. */
export function pathRules(config = { exclude: [], tests: [] }) {
  const excluded = config.exclude.map(globMatcher);
  const tests = config.tests.map(globMatcher);
  return {
    /** Why a path is not measured, or null. */
    exclusion(file) {
      const parts = file.split('/');
      const base = parts[parts.length - 1];
      if (parts.slice(0, -1).some((part) => EXCLUDED_DIRS.has(part))) return 'excluded folder';
      if (LOCKFILES.has(base)) return 'lockfile';
      if (MINIFIED_NAME.test(base)) return 'minified';
      if (NOT_CODE_EXTENSIONS.has(extensionOf(base))) return 'not code';
      if (DOCUMENT_EXTENSIONS.has(extensionOf(base)) || DOCUMENT_NAMES.test(base)) return 'documentation';
      if (excluded.some((match) => match(file))) return 'repository exclusion';
      return null;
    },
    isTest(file) {
      const parts = file.split('/');
      if (parts.slice(0, -1).some((part) => TEST_DIR.test(part))) return true;
      if (TEST_NAMES.some((pattern) => pattern.test(file))) return true;
      return tests.some((match) => match(file));
    },
  };
}

/** Why a file's own bytes rule it out: written by a tool, minified, or binary. Null when it is measured. */
export function contentExclusion(file, head, { size = head.length, lines = null } = {}) {
  if (head.includes(0)) return 'binary';
  const text = head.toString('utf8');
  const top = text.split('\n').slice(0, 5);
  if (top.some((line) => COMMENT_LINE.test(line) && GENERATED_MARKER.test(line))) return 'generated';
  if (lines !== null && ['js', 'mjs', 'cjs', 'css'].includes(extensionOf(file)) && size > 2048 && size / Math.max(lines, 1) > 255) return 'minified';
  return null;
}

/** Only the paths under the measured folders, when there are any. */
export function underPaths(file, paths) {
  return !paths || paths.some((prefix) => file === prefix || file.startsWith(`${prefix}/`));
}

/**
 * The files measured, from git's list of tracked files: each regular file
 * inside the repository that no rule excludes, marked test or code.
 */
export function selectFiles(repo, tracked, { paths = null, config, io = fs } = {}) {
  const rules = pathRules(config);
  const realRepo = io.realpathSync(repo);
  const files = [];
  const skipped = new Set();
  for (const raw of tracked) {
    const file = safeRelativePath(raw);
    if (!file || !underPaths(file, paths)) continue;
    if (rules.exclusion(file)) continue;
    const full = path.join(repo, file);
    let stat;
    try { stat = io.lstatSync(full); } catch { continue; }
    if (!stat.isFile()) continue;
    try {
      if (!io.realpathSync(full).startsWith(`${realRepo}${path.sep}`)) continue;
    } catch { continue; }
    let fd;
    try { fd = io.openSync(full, 'r'); } catch { continue; }
    let reason;
    try {
      const minifiable = ['js', 'mjs', 'cjs', 'css'].includes(extensionOf(file)) && stat.size > 2048 && stat.size <= 4 * 1024 * 1024;
      const head = Buffer.alloc(minifiable ? stat.size : Math.min(stat.size, 8192));
      const read = io.readSync(fd, head, 0, head.length, 0);
      const bytes = head.subarray(0, read);
      let lines = null;
      if (minifiable) { lines = 1; for (const byte of bytes) if (byte === 10) lines += 1; }
      reason = contentExclusion(file, minifiable ? bytes.subarray(0, 8192) : bytes, { size: stat.size, lines });
    } finally { io.closeSync(fd); }
    if (reason) { skipped.add(file); continue; }
    files.push({ path: file, test: rules.isTest(file) });
  }
  return { files, skipped, rules };
}

