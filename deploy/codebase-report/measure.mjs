function run(command, args, { cwd, timeoutMs = 600_000, env } = {}) {
  return new Promise((resolve) => {
    execFile(command, args, { cwd, timeout: timeoutMs, maxBuffer: 512 * 1024 * 1024, encoding: 'utf8', env: env ?? process.env },
      (error, stdout, stderr) => resolve({ ok: !error, code: error ? (error.code ?? 1) : 0, stdout, stderr: String(stderr ?? '').slice(-2000) }));
  });
}

/**
 * Git with nothing from the repository able to start a program. The mounted
 * checkout belongs to another user than the image's, which git refuses to
 * read unless this one command marks it safe.
 */
function gitArgs(repo, args) {
  return ['-c', 'safe.directory=*', '-c', 'core.fsmonitor=false', '-c', 'core.hooksPath=/dev/null',
    '-c', 'log.showSignature=false', '-C', repo, ...args];
}
async function git(repo, args, options) {
  return run('git', gitArgs(repo, args), options);
}

/** Batches of paths small enough for one command line. */
export function batches(files, { maxFiles = 2000, maxChars = 100_000 } = {}) {
  const out = [];
  let current = [];
  let chars = 0;
  for (const file of files) {
    if (current.length && (current.length >= maxFiles || chars + file.length + 1 > maxChars)) { out.push(current); current = []; chars = 0; }
    current.push(file);
    chars += file.length + 1;
  }
  if (current.length) out.push(current);
  return out;
}

const LIZARD_HOME = process.env.NOTICEOS_LIZARD_HOME || '/opt/lizard';
// -I keeps Python from importing anything from the working folder or the environment.
const LIZARD_BOOT = 'import sys; sys.path.insert(0, sys.argv.pop(1)); import lizard; sys.argv[0] = "lizard"; sys.exit(lizard.main())';
const lizard = (args, options) => run('python3', ['-I', '-c', LIZARD_BOOT, LIZARD_HOME, ...args], options);

async function toolVersions() {
  const [scc, jscpd, liz] = await Promise.all([run('scc', ['--version']), run('jscpd', ['--version']), lizard(['--version'])]);
  const tools = {};
  const image = process.env.NOTICEOS_CODEBASE_IMAGE;
  if (image && IMAGE_DIGEST.test(image)) tools.image = image;
  for (const [name, result] of [['scc', scc], ['jscpd', jscpd], ['lizard', liz]]) {
    const version = result.ok ? versionOf(result.stdout || result.stderr) : null;
    if (version) tools[name] = version;
  }
  return tools;
}

async function measureSize(repo, files, testPaths, tools, log) {
  if (!tools.scc) return { unmeasured: allReasons(['code_lines', 'comment_lines', 'files', 'languages', 'test_lines', 'test_ratio'], REASONS.sccFailed) };
  const rows = [];
  for (const batch of batches(files.map((file) => file.path))) {
    const result = await run('scc', ['--by-file', '--format', 'json', '--no-cocomo', '--no-complexity', '--no-gitignore',
      '--no-ignore', '--no-scc-ignore', '--no-gitmodule', '--', ...batch], { cwd: repo });
    if (!result.ok) {
      log(`scc failed: ${result.stderr}`);
      return { unmeasured: allReasons(['code_lines', 'comment_lines', 'files', 'languages', 'test_lines', 'test_ratio'], REASONS.sccFailed) };
    }
    rows.push(...parseScc(result.stdout));
  }
  return sizeSummary(rows, testPaths);
}

function allReasons(keys, reason) { return Object.fromEntries(keys.map((key) => [key, reason])); }

async function jscpdReport(repo, files, work, extra, reportName) {
  const output = fs.mkdtempSync(path.join(work, 'jscpd-'));
  const config = path.join(output, 'config.json');
  fs.writeFileSync(config, JSON.stringify({ path: files.map((file) => path.join(repo, file)), reporters: ['json'], output, absolute: true, silent: true }));
  const result = await run('jscpd', ['--config', config, '--no-gitignore', '--no-tips', '--silent', ...extra], { cwd: output, timeoutMs: 1_800_000 });
  // The clone report is jscpd-report.json; the dead-code report's name differs by version, so it is the one other file.
  const report = fs.readdirSync(output).find((name) => name !== 'config.json' && name.endsWith('.json') && (!reportName || name === reportName));
  if (!result.ok || !report) throw new Error(`jscpd failed: ${result.stderr}`);
  return fs.readFileSync(path.join(output, report), 'utf8');
}

async function measureDuplication(repo, codeFiles, work, log) {
  const keys = ['duplicated_lines', 'duplication_percent', 'duplicate_blocks'];
  if (codeFiles.length === 0) return { unmeasured: allReasons(keys, REASONS.noFiles) };
  try {
    const text = await jscpdReport(repo, codeFiles, work, [], 'jscpd-report.json');
    return parseJscpd(text, { repo, measured: new Set(codeFiles) });
  } catch (error) {
    log(error.message);
    return { unmeasured: allReasons(keys, REASONS.jscpdFailed) };
  }
}

async function measureUnused(repo, allFiles, codeFiles, paths, work, log) {
  const keys = ['unused_files', 'unused_exports'];
  const checked = codeFiles.filter((file) => DEAD_CODE_EXTENSIONS.has(extensionOf(file)));
  if (checked.length === 0) return { unmeasured: allReasons(keys, REASONS.deadCodeLanguages) };
  try {
    // Tests are read so that what only they import counts as used; unused code inside tests is not reported.
    const text = await jscpdReport(repo, allFiles, work, ['--dead-code']);
    return parseDeadCode(text, { repo, measured: new Set(codeFiles), paths });
  } catch (error) {
    log(error.message);
    return { unmeasured: allReasons(keys, REASONS.deadCodeFailed) };
  }
}

async function measureComplexity(repo, codeFiles, work, log) {
  const keys = ['functions', 'complex_functions', 'max_function_complexity', 'mean_function_complexity'];
  const readable = codeFiles.filter((file) => LIZARD_EXTENSIONS.has(extensionOf(file)) || extensionOf(file) in LIZARD_ALIASES);
  if (readable.length === 0) return { unmeasured: allReasons(keys, REASONS.lizardLanguages) };
  // lizard picks a language by extension; a .mts or .cts file is read through a .ts link to it.
  const links = fs.mkdtempSync(path.join(work, 'lizard-'));
  const byRead = new Map();
  const list = readable.map((file, index) => {
    const alias = LIZARD_ALIASES[extensionOf(file)];
    const full = path.join(repo, file);
    if (!alias) { byRead.set(full, file); return full; }
    const link = path.join(links, `${index}.${alias}`);
    fs.symlinkSync(full, link);
    byRead.set(link, file);
    return link;
  });
  const listFile = path.join(links, 'files.txt');
  fs.writeFileSync(listFile, `${list.join('\n')}\n`);
  const threads = String(Math.max(1, Math.min(4, os.availableParallelism?.() ?? 1)));
  const result = await lizard(['--csv', '--no-gitignore', '--ignore_warnings=-1', '-t', threads, '-f', listFile], { cwd: links, timeoutMs: 1_800_000 });
  if (!result.ok) {
    log(`lizard failed: ${result.stderr}`);
    return { unmeasured: allReasons(keys, REASONS.lizardFailed) };
  }
  const summary = complexitySummary(parseLizard(result.stdout, (read) => byRead.get(read) ?? null));
  if (summary.measures.functions === 0) summary.unmeasured = allReasons(['max_function_complexity', 'mean_function_complexity'], REASONS.noFunctions);
  return summary;
}

async function measureChurn(repo, paths, counted, now, log) {
  const keys = ['commits_30d', 'files_touched_30d', 'large_commits_30d'];
  const since = Math.floor((now.getTime() - CHURN_DAYS * DAY_MS) / 1000);
  const shallow = await git(repo, ['rev-parse', '--is-shallow-repository']);
  if (!shallow.ok) return { unmeasured: allReasons(keys, REASONS.gitFailed) };
  if (shallow.stdout.trim() === 'true') {
    // A shallow checkout still measures the window when its oldest commit is older than the window's start.
    const times = await git(repo, ['log', '--format=%ct', 'HEAD']);
    if (!times.ok) return { unmeasured: allReasons(keys, REASONS.gitFailed) };
    const oldest = times.stdout.split('\n').filter(Boolean).map(Number).reduce((low, time) => Math.min(low, time), Infinity);
    if (!(oldest <= since)) return { unmeasured: allReasons(keys, REASONS.shallow) };
  }
  const result = await git(repo, ['log', '--no-merges', '--no-renames', '--no-textconv', '--no-ext-diff', `--since=@${since}`,
    '--format=%x1e%H', '--numstat', '-z', 'HEAD', '--', ...(paths ?? ['.'])]);
  if (!result.ok) {
    log(`git log failed: ${result.stderr}`);
    return { unmeasured: allReasons(keys, REASONS.gitFailed) };
  }
  return { measures: churnSummary(parseGitLog(result.stdout), counted) };
}

async function repositoryFacts(repo, ref) {
  const [commit, committed, branch, remote] = await Promise.all([
    git(repo, ['rev-parse', '--verify', 'HEAD^{commit}']),
    git(repo, ['show', '-s', '--no-show-signature', '--format=%cI', 'HEAD']),
    git(repo, ['rev-parse', '--abbrev-ref', 'HEAD']),
    git(repo, ['config', '--get', 'remote.origin.url']),
  ]);
  const hash = commit.stdout.trim();
  if (!commit.ok || !/^[a-f0-9]{40}$/u.test(hash)) throw new Error(`${repo} is not a git checkout with a commit (git rev-parse HEAD failed).`);
  const facts = {};
  const address = remote.ok ? normalizeRemote(remote.stdout) : null;
  if (address) facts.remote = address;
  const name = ref ?? branch.stdout.trim();
  facts.ref = REF.test(name) ? name : 'HEAD';
  facts.commit = hash;
  facts.committedAt = isoSeconds(committed.stdout.trim());
  return facts;
}

function readRepoConfigFile(repo) {
  const file = path.join(repo, '.noticeos-codebase.json');
  let stat;
  try { stat = fs.lstatSync(file); } catch { return readRepoConfig(null); }
  if (!stat.isFile() || stat.size > 65_536) throw new Error('.noticeos-codebase.json must be a regular file under 64 KiB.');
  return readRepoConfig(fs.readFileSync(file, 'utf8'));
}

/** Measure `repo` and return the envelope. */
export async function measure({ asset, repo, paths = null, ref = null, now = new Date(), log = (line) => process.stderr.write(`${line}\n`) }) {
  const stat = fs.statSync(repo, { throwIfNoEntry: false });
  if (!stat?.isDirectory()) throw new Error(`${repo} is not a folder.`);
  for (const prefix of paths ?? []) {
    if (!fs.existsSync(path.join(repo, prefix))) throw new Error(`--paths names ${prefix}, which is not in the repository.`);
  }
  const repository = await repositoryFacts(repo, ref);
  const config = readRepoConfigFile(repo);
  const listed = await git(repo, ['ls-files', '-z', '--cached']);
  if (!listed.ok) throw new Error(`git ls-files failed: ${listed.stderr}`);
  const { files, skipped, rules } = selectFiles(repo, listed.stdout.split('\0').filter(Boolean), { paths, config });
  const allPaths = files.map((file) => file.path);
  const codePaths = files.filter((file) => !file.test).map((file) => file.path);
  const testPaths = new Set(files.filter((file) => file.test).map((file) => file.path));
  const tools = await toolVersions();
  const work = fs.mkdtempSync(path.join(os.tmpdir(), 'noticeos-codebase-'));
  try {
    const measures = {};
    const unmeasured = { unused_dependencies: REASONS.unusedDependencies };
    const take = (part) => {
      Object.assign(measures, part.measures ?? {});
      for (const [key, reason] of Object.entries(part.unmeasured ?? {})) unmeasured[key] ??= reason;
    };
    const missing = (tool, keys, reason) => (tools[tool] ? null : { unmeasured: allReasons(keys, reason) });
    const size = await measureSize(repo, files, testPaths, tools, log);
    const duplication = missing('jscpd', ['duplicated_lines', 'duplication_percent', 'duplicate_blocks'], REASONS.jscpdFailed)
      ?? await measureDuplication(repo, codePaths, work, log);
    const unused = missing('jscpd', ['unused_files', 'unused_exports'], REASONS.deadCodeFailed)
      ?? await measureUnused(repo, allPaths, codePaths, paths, work, log);
    const complexity = missing('lizard', ['functions', 'complex_functions', 'max_function_complexity', 'mean_function_complexity'], REASONS.lizardFailed)
      ?? await measureComplexity(repo, codePaths, work, log);
    const counted = (file) => underPaths(file, paths) && !rules.exclusion(file) && !skipped.has(file);
    const churn = await measureChurn(repo, paths, counted, now, log);
    for (const part of [size, duplication, unused, complexity, churn]) take(part);
    const manifests = codePaths.filter((file) => MANIFEST_NAME.test(file))
      .map((file) => ({ file, text: fs.readFileSync(path.join(repo, file), 'utf8') }));
    const dependencies = directDependencies(manifests);
    if (dependencies === null) unmeasured.dependencies_direct = REASONS.noManifest;
    else measures.dependencies_direct = dependencies;
    return buildEnvelope({
      asset,
      generatedAt: isoSeconds(now),
      repository,
      paths,
      tools,
      measures,
      unmeasured,
      byLanguage: size.byLanguage,
      // A list is left out when its tool did not run, so an empty list always means none were found.
      findings: {
        duplicates: duplication.duplicates,
        complexFunctions: complexity.complexFunctions,
        unused: unused.unused,
        largestFiles: size.largestFiles,
      },
    });
  } finally {
    fs.rmSync(work, { recursive: true, force: true });
  }
}

/** Send the envelope to the ingest; resolves the ingest's answer. */
export async function postEnvelope(endpoint, envelope, token, fetchImpl = fetch) {
  const response = await fetchImpl(endpoint, {
    method: 'POST',
    headers: { authorization: `Bearer ${token}`, 'content-type': 'application/json' },
    body: JSON.stringify(envelope),
    signal: AbortSignal.timeout(60_000),
  });
  const text = await response.text().catch(() => '');
  return { status: response.status, ok: response.status === 201, body: text.slice(0, 1000) };
}

/** One line a person reads after a run. */
export function summaryLine(envelope) {
  const m = envelope.measures;
  const parts = [];
  if (m.code_lines !== undefined) parts.push(`${m.code_lines} lines of code`);
  if (m.duplication_percent !== undefined) parts.push(`${m.duplication_percent}% repeated`);
  if (m.unused_files !== undefined) parts.push(`${m.unused_files} unused files`);
  if (m.complex_functions !== undefined) parts.push(`${m.complex_functions} hard-to-change functions`);
  const unmeasured = Object.keys(envelope.unmeasured ?? {});
  return `${envelope.asset} at ${envelope.repository.commit.slice(0, 12)}: ${parts.join(', ') || 'nothing measured'}`
    + `${unmeasured.length ? `; not measured: ${unmeasured.join(', ')}` : ''}.`;
}

export async function main(argv = process.argv.slice(2), { env = process.env, out = process.stdout, err = process.stderr, fetchImpl = fetch } = {}) {
  if (argv.length === 1 && ['--help', '-h'].includes(argv[0])) { out.write(`${HELP}\n`); return 0; }
  let options;
  try { options = parseArgs(argv); } catch (error) { err.write(`${error.message}\n`); return 2; }
  const token = env.NOTICEOS_ASSET_TOKEN ?? '';
  if (options.post && !token) { err.write('--post needs the site token in NOTICEOS_ASSET_TOKEN.\n'); return 2; }
  let envelope;
  try {
    envelope = await measure({ ...options, log: (line) => err.write(`${line}\n`) });
  } catch (error) {
    err.write(`${error.message}\n`);
    return 1;
  }
  const body = `${JSON.stringify(envelope, null, 2)}\n`;
  if (options.out) fs.writeFileSync(options.out, body);
  if (!options.out && !options.post) out.write(body);
  err.write(`${summaryLine(envelope)}\n`);
  if (!options.post) return 0;
  try {
    const answer = await postEnvelope(options.post, envelope, token, fetchImpl);
    if (answer.ok) { err.write(`The ingest stored the report: ${answer.body}\n`); return 0; }
    err.write(`The ingest refused the report (${answer.status}): ${answer.body}\n`);
    if (answer.status === 401) err.write('The token does not match the site id; both come from the site in the Tower.\n');
    return 1;
  } catch (error) {
    err.write(`The report could not be sent: ${error.message}\n`);
    return 1;
  }
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) process.exitCode = await main();
