/** One row per file from `scc --by-file --format json`. */
export function parseScc(text) {
  const languages = JSON.parse(text);
  if (!Array.isArray(languages)) throw new Error('scc output is not a list of languages.');
  const rows = [];
  for (const language of languages) {
    for (const file of language?.Files ?? []) {
      const where = safeRelativePath(String(file.Location ?? '').replace(/^\.\//u, ''));
      if (!where) continue;
      rows.push({
        path: where,
        language: String(file.Language ?? language.Name ?? 'Other'),
        code: Number(file.Code) || 0,
        comment: Number(file.Comment) || 0,
      });
    }
  }
  return rows;
}

/** `--version` lines: the first dotted version number in each. */
export function versionOf(text) {
  return /\b(\d+\.\d+\.\d+(?:[-+][0-9A-Za-z.-]+)?)\b/u.exec(String(text))?.[1] ?? null;
}

/** A tool's path as a repository-relative path, whether it printed it absolute or relative. */
export function repoRelative(repo, file) {
  if (typeof file !== 'string') return null;
  const posixRepo = repo.split(path.sep).join('/').replace(/\/+$/u, '');
  const posixFile = file.split(path.sep).join('/');
  if (posixFile.startsWith(`${posixRepo}/`)) return safeRelativePath(posixFile.slice(posixRepo.length + 1));
  return posixFile.startsWith('/') ? null : safeRelativePath(posixFile);
}

/** jscpd's clone report: totals and the clone list, paths only. */
export function parseJscpd(text, { repo, measured }) {
  const report = JSON.parse(text);
  const total = report?.statistics?.total;
  if (!total || typeof total !== 'object') throw new Error('jscpd report has no totals.');
  const duplicates = [];
  for (const clone of report.duplicates ?? []) {
    const files = [clone.firstFile, clone.secondFile].map((side) => ({
      path: repoRelative(repo, side?.name), startLine: Number(side?.start ?? side?.startLoc?.line),
    }));
    if (files.some((side) => !side.path || !measured.has(side.path) || !Number.isInteger(side.startLine) || side.startLine < 1)) continue;
    const lines = Number(clone.lines);
    if (!Number.isInteger(lines) || lines < 1) continue;
    duplicates.push({ lines, files });
  }
  duplicates.sort((a, b) => b.lines - a.lines || a.files[0].path.localeCompare(b.files[0].path) || a.files[0].startLine - b.files[0].startLine);
  return {
    measures: {
      duplicated_lines: Math.max(0, Math.round(Number(total.duplicatedLines) || 0)),
      duplication_percent: clamp(round(Number(total.percentage) || 0, 1), 0, 100),
      duplicate_blocks: Math.max(0, Math.round(Number(total.clones) || 0)),
    },
    duplicates,
  };
}

/** jscpd --dead-code's report: unused files and exports, paths and names only. */
export function parseDeadCode(text, { repo, measured, paths = null }) {
  const report = JSON.parse(text);
  if (!Array.isArray(report?.findings)) throw new Error('jscpd dead-code report has no findings list.');
  const resolve = (file) => {
    const direct = repoRelative(repo, file);
    if (direct && measured.has(direct)) return direct;
    for (const prefix of paths ?? []) {
      const joined = direct && safeRelativePath(`${prefix}/${direct}`);
      if (joined && measured.has(joined)) return joined;
    }
    return null;
  };
  const files = [];
  const exports = [];
  for (const finding of report.findings) {
    const where = resolve(finding?.path);
    if (!where) continue;
    const lines = Number(finding.lines) || 0;
    if (finding.category === 'unused-file') files.push({ kind: 'file', path: where, lines });
    else if (finding.category === 'unused-export' && typeof finding.name === 'string' && finding.name) {
      exports.push({ kind: 'export', path: where, name: finding.name.slice(0, LIMITS.nameChars), lines });
    }
  }
  const byLines = (a, b) => b.lines - a.lines || a.path.localeCompare(b.path) || (a.name ?? '').localeCompare(b.name ?? '');
  files.sort(byLines);
  exports.sort(byLines);
  return {
    measures: { unused_files: files.length, unused_exports: exports.length },
    unused: [...files, ...exports].map(({ lines: _lines, ...row }) => row),
  };
}

/** Split CSV text into rows of fields, with quoted fields and doubled quotes. */
export function parseCsv(text) {
  const rows = [];
  let row = [];
  let field = '';
  let quoted = false;
  for (let i = 0; i < text.length; i += 1) {
    const char = text[i];
    if (quoted) {
      if (char === '"' && text[i + 1] === '"') { field += '"'; i += 1; } else if (char === '"') quoted = false;
      else field += char;
    } else if (char === '"') quoted = true;
    else if (char === ',') { row.push(field); field = ''; } else if (char === '\n' || char === '\r') {
      if (char === '\r' && text[i + 1] === '\n') i += 1;
      row.push(field); field = '';
      if (row.length > 1 || row[0] !== '') rows.push(row);
      row = [];
    } else field += char;
  }
  if (field !== '' || row.length) { row.push(field); rows.push(row); }
  return rows;
}

/**
 * lizard --csv: NLOC, CCN, token, PARAM, length, location, file, function,
 * long_name, start, end. `mapPath` turns the path lizard read into the
 * measured file's repository path.
 */
export function parseLizard(text, mapPath) {
  const functions = [];
  for (const fields of parseCsv(text)) {
    if (fields.length < 11 || fields[1] === 'CCN') continue;
    const complexity = Number(fields[1]);
    const length = Number(fields[4]);
    const line = Number(fields[9]);
    const where = mapPath(fields[6]);
    if (!where || !Number.isInteger(complexity) || complexity < 1 || !Number.isInteger(line) || line < 1) continue;
    functions.push({ path: where, name: (fields[7] || '(anonymous)').slice(0, LIMITS.nameChars), line, complexity, length: Number.isInteger(length) && length > 0 ? length : 1 });
  }
  return functions;
}

/** The complexity measures and the hardest functions. */
export function complexitySummary(functions) {
  if (functions.length === 0) return { measures: { functions: 0, complex_functions: 0 }, complexFunctions: [] };
  const complex = functions.filter((fn) => fn.complexity > COMPLEX_ABOVE);
  const total = functions.reduce((sum, fn) => sum + fn.complexity, 0);
  complex.sort((a, b) => b.complexity - a.complexity || b.length - a.length || a.path.localeCompare(b.path) || a.line - b.line);
  return {
    measures: {
      functions: functions.length,
      complex_functions: complex.length,
      max_function_complexity: Math.max(...functions.map((fn) => fn.complexity)),
      mean_function_complexity: round(total / functions.length, 1),
    },
    complexFunctions: complex,
  };
}

/** `git log --format=%x1e%H --numstat -z`: one entry per commit with the paths it touched. */
export function parseGitLog(text) {
  const commits = [];
  for (const record of text.split('\x1e')) {
    if (!record.trim()) continue;
    const nul = record.indexOf('\0');
    const hash = (nul === -1 ? record : record.slice(0, nul)).trim();
    if (!/^[a-f0-9]{40,64}$/u.test(hash)) continue;
    const files = [];
    for (const entry of (nul === -1 ? '' : record.slice(nul + 1)).split('\0')) {
      const match = /^\n?(?:\d+|-)\t(?:\d+|-)\t(.+)$/su.exec(entry);
      if (match) files.push(match[1]);
    }
    commits.push({ hash, files });
  }
  return commits;
}

/** The change measures over the commits read, counting only files the rules measure. */
export function churnSummary(commits, counted) {
  const touched = new Set();
  let changes = 0;
  let large = 0;
  for (const commit of commits) {
    const files = commit.files.map(safeRelativePath).filter((file) => file && counted(file));
    if (files.length === 0) continue;
    changes += 1;
    if (new Set(files).size >= LARGE_COMMIT_FILES) large += 1;
    for (const file of files) touched.add(file);
  }
  return { commits_30d: changes, files_touched_30d: touched.size, large_commits_30d: large };
}

/** The repository's address without scheme, credentials or `.git`, or null when it is not a plain host/path. */
export function normalizeRemote(value) {
  if (typeof value !== 'string') return null;
  let text = value.trim();
  const scp = /^[^@/\s]+@([^:/\s]+):(.+)$/u.exec(text);
  if (scp) text = `${scp[1]}/${scp[2]}`;
  else {
    try {
      const url = new URL(text);
      if (!['https:', 'http:', 'ssh:', 'git:'].includes(url.protocol)) return null;
      text = `${url.host}${url.pathname}`;
    } catch { return null; }
  }
  text = text.replace(/\/+$/u, '').replace(/\.git$/u, '');
  return /^[A-Za-z0-9.-]+(?::\d+)?(?:\/[A-Za-z0-9._~-]+)+$/u.test(text) && text.length <= 300 ? text : null;
}

