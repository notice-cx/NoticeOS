const LOCAL_SPEC = /^(?:workspace|link|file|portal):/u;
const MANIFEST_NAME = /(?:^|\/)(?:package\.json|requirements[\w.-]*\.txt|go\.mod|Cargo\.toml)$/u;

/** Direct dependency names from one manifest, prefixed with its ecosystem; null when the file is not one. */
export function manifestDependencies(file, text) {
  const base = file.slice(file.lastIndexOf('/') + 1);
  const names = new Set();
  if (base === 'package.json') {
    let value;
    try { value = JSON.parse(text); } catch { return null; }
    for (const key of ['dependencies', 'devDependencies', 'optionalDependencies']) {
      for (const [name, spec] of Object.entries(value?.[key] ?? {})) {
        if (typeof spec === 'string' && LOCAL_SPEC.test(spec)) continue;
        names.add(`npm:${name}`);
      }
    }
    return { names, own: typeof value?.name === 'string' ? `npm:${value.name}` : null };
  }
  if (/^requirements[\w.-]*\.txt$/u.test(base)) {
    for (const raw of text.split('\n')) {
      const line = raw.replace(/#.*$/u, '').trim();
      const match = /^([A-Za-z0-9][A-Za-z0-9._-]*)/u.exec(line);
      if (match && !line.startsWith('-')) names.add(`pypi:${match[1].toLowerCase().replace(/[-_.]+/gu, '-')}`);
    }
    return { names, own: null };
  }
  if (base === 'go.mod') {
    let block = false;
    for (const raw of text.split('\n')) {
      const line = raw.trim();
      if (/^require\s*\($/u.test(line)) { block = true; continue; }
      if (block && line === ')') { block = false; continue; }
      const entry = block ? line : /^require\s+(.+)$/u.exec(line)?.[1];
      if (!entry || entry.includes('// indirect')) continue;
      const name = /^(\S+)\s+v\S+/u.exec(entry)?.[1];
      if (name) names.add(`go:${name}`);
    }
    return { names, own: null };
  }
  if (base === 'Cargo.toml') {
    let section = '';
    for (const raw of text.split('\n')) {
      const line = raw.replace(/#.*$/u, '').trim();
      const header = /^\[([^\]]+)\]$/u.exec(line);
      if (header) {
        section = header[1].trim();
        const table = /(?:^|\.)(?:dev-|build-)?dependencies\.([A-Za-z0-9_-]+)$/u.exec(section);
        if (table) names.add(`cargo:${table[1]}`);
        continue;
      }
      if (!/(?:^|\.)(?:dev-|build-)?dependencies$/u.test(section)) continue;
      const key = /^([A-Za-z0-9_-]+)\s*=/u.exec(line)?.[1];
      if (key) names.add(`cargo:${key}`);
    }
    return { names, own: null };
  }
  return null;
}

/** How many distinct direct dependencies the measured manifests name; the workspace's own packages are not counted. */
export function directDependencies(manifests) {
  const all = new Set();
  const own = new Set();
  let found = 0;
  for (const { file, text } of manifests) {
    const parsed = manifestDependencies(file, text);
    if (!parsed) continue;
    found += 1;
    for (const name of parsed.names) all.add(name);
    if (parsed.own) own.add(parsed.own);
  }
  if (found === 0) return null;
  for (const name of own) all.delete(name);
  return all.size;
}

