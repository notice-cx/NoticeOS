function round(value, places) {
  const factor = 10 ** places;
  return Math.round(value * factor) / factor;
}
function clamp(value, low, high) { return Math.min(high, Math.max(low, value)); }
/** An ISO instant in UTC without milliseconds. */
export function isoSeconds(date) { return new Date(date).toISOString().replace(/\.\d{3}Z$/u, 'Z'); }

/** Line counts, languages, the largest files and the test share, from scc's rows. */
export function sizeSummary(rows, testPaths) {
  const code = rows.filter((row) => !testPaths.has(row.path));
  const tests = rows.filter((row) => testPaths.has(row.path));
  const languages = new Map();
  for (const row of code) {
    const entry = languages.get(row.language) ?? { language: row.language, files: 0, code_lines: 0 };
    entry.files += 1;
    entry.code_lines += row.code;
    languages.set(row.language, entry);
  }
  const codeLines = code.reduce((sum, row) => sum + row.code, 0);
  const testLines = tests.reduce((sum, row) => sum + row.code, 0);
  const measures = {
    code_lines: codeLines,
    comment_lines: code.reduce((sum, row) => sum + row.comment, 0),
    files: code.length,
    languages: languages.size,
    test_lines: testLines,
  };
  const unmeasured = {};
  // Test lines over code lines, uncapped: a codebase with more test than code reads above 1.
  if (codeLines > 0) measures.test_ratio = round(testLines / codeLines, 2);
  else unmeasured.test_ratio = REASONS.noTests;
  return {
    measures,
    unmeasured,
    byLanguage: [...languages.values()].sort((a, b) => b.code_lines - a.code_lines || a.language.localeCompare(b.language)),
    largestFiles: code.filter((row) => row.code > 0).sort((a, b) => b.code - a.code || a.path.localeCompare(b.path))
      .map((row) => ({ path: row.path, code_lines: row.code })),
  };
}

const MEASURE_ORDER = ['code_lines', 'comment_lines', 'files', 'languages', 'duplicated_lines', 'duplication_percent',
  'duplicate_blocks', 'unused_files', 'unused_exports', 'unused_dependencies', 'dependencies_direct', 'functions',
  'complex_functions', 'max_function_complexity', 'mean_function_complexity', 'test_lines', 'test_ratio', 'commits_30d',
  'files_touched_30d', 'large_commits_30d'];

/**
 * The envelope within the contract's bounds: every list cut to its limit,
 * every path checked, and the findings halved until the body fits. Measures
 * are never cut, only findings.
 */
export function boundEnvelope(envelope, { bodyBytes = LIMITS.bodyBytes } = {}) {
  const keep = (value) => safeRelativePath(value) === value;
  const out = structuredClone(envelope);
  if (out.byLanguage) out.byLanguage = out.byLanguage.slice(0, LIMITS.byLanguage);
  else delete out.byLanguage;
  const given = out.findings ?? {};
  const findings = {};
  if (given.duplicates) {
    findings.duplicates = given.duplicates
      .map((row) => ({ ...row, files: row.files.filter((file) => keep(file.path)).slice(0, LIMITS.duplicateFiles) }))
      .filter((row) => row.files.length >= 2).slice(0, LIMITS.duplicates);
  }
  if (given.complexFunctions) findings.complexFunctions = given.complexFunctions.filter((row) => keep(row.path)).slice(0, LIMITS.complexFunctions);
  if (given.unused) findings.unused = given.unused.filter((row) => row.kind === 'dependency' || keep(row.path)).slice(0, LIMITS.unused);
  if (given.largestFiles) findings.largestFiles = given.largestFiles.filter((row) => keep(row.path)).slice(0, LIMITS.largestFiles);
  out.findings = findings;
  const size = () => Buffer.byteLength(JSON.stringify(out));
  for (const key of ['unused', 'duplicates', 'complexFunctions', 'largestFiles']) {
    while (size() > bodyBytes && findings[key]?.length > 0) findings[key] = findings[key].slice(0, Math.floor(findings[key].length / 2));
  }
  if (size() > bodyBytes) throw new Error(`The report is larger than ${bodyBytes} bytes even without its findings.`);
  return out;
}

/** The envelope from everything measured, keys in the contract's order. */
export function buildEnvelope({ asset, generatedAt, repository, paths, tools, measures, unmeasured, byLanguage, findings }) {
  const orderedMeasures = {};
  for (const key of MEASURE_ORDER) if (Number.isFinite(measures[key])) orderedMeasures[key] = measures[key];
  const orderedUnmeasured = {};
  for (const key of MEASURE_ORDER) {
    if (!(key in orderedMeasures) && unmeasured[key]) orderedUnmeasured[key] = unmeasured[key].slice(0, LIMITS.reasonChars);
  }
  return boundEnvelope({
    asset,
    generatedAt,
    repository,
    ...(paths ? { paths } : {}),
    tools,
    measures: orderedMeasures,
    ...(Object.keys(orderedUnmeasured).length ? { unmeasured: orderedUnmeasured } : {}),
    ...(byLanguage ? { byLanguage } : {}),
    findings: Object.fromEntries(Object.entries(findings ?? {}).filter(([, list]) => Array.isArray(list))),
  });
}

