#!/usr/bin/env node
// Precise's tokens for the Tower, generated from the installed @notice-cx/ntasks-ui stylesheet.
//
// The Tower draws in Ntasks's design system, Precise, with the Notice blue.
// Its values live in one place, the Ntasks UI package's stylesheet, where
// every token applies only inside `[data-ntasks]`. This writes them out as
// `--precise-<name>` variables for the Tower's own pages, dark by default and
// light under `.light`, as public/brand/notice.css switches its own, so the
// Tower's names point at Precise's values instead of keeping a second copy.
// `pnpm generate -- --check` fails when the committed file no longer matches
// the installed package, such as after a version bump that changed a value.
//
//   node scripts/precise-tokens.mjs            print the stylesheet
//   node scripts/precise-tokens.mjs --write    rewrite apps/tower/public/brand/precise.css
//   node scripts/precise-tokens.mjs --check    exit 1 when it is stale

import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { invokedDirectly } from './invoked-directly.mjs';

export const REPO_ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
export const OUTPUT = 'apps/tower/public/brand/precise.css';
const PACKAGE = '@notice-cx/ntasks-ui';

/** The installed package's stylesheet and version, as the Tower resolves them. */
export function installedStylesheet(root = REPO_ROOT) {
  const require = createRequire(path.join(root, 'apps/tower/package.json'));
  const css = readFileSync(require.resolve(`${PACKAGE}/styles.css`), 'utf8');
  const manifest = path.join(path.dirname(require.resolve(`${PACKAGE}/styles.css`)), '..', 'package.json');
  return { css, version: JSON.parse(readFileSync(manifest, 'utf8')).version };
}

/** `#abc` as `#aabbcc`, so every value reads one way. */
const longHex = (value) => value.replace(/^#([\da-f])([\da-f])([\da-f])$/iu, '#$1$1$2$2$3$3').toLowerCase();

/** The custom properties of the rule whose selector list holds `selector`. */
function themeBlock(css, selector) {
  for (const match of css.matchAll(/([^{}]+)\{([^{}]*)\}/gu)) {
    const selectors = match[1].split(',').map((one) => one.trim());
    if (!selectors.includes(selector)) continue;
    const tokens = new Map();
    for (const [, name, value] of match[2].matchAll(/--([a-z][a-z0-9-]*):([^;]+)/gu)) {
      // The colours, the shadows and the marks; the workspace icons' own
      // palette is the package's alone, and the rest is its build's.
      if (/^(lightningcss|tw-|identity-)/u.test(name)) continue;
      tokens.set(name, longHex(value.trim()));
    }
    return tokens;
  }
  throw new Error(`${PACKAGE}'s stylesheet has no rule for ${selector}: its theme blocks moved, so scripts/precise-tokens.mjs reads it no longer.`);
}

/** Precise's tokens in each theme, read from the package's stylesheet. */
export function preciseTokens(css) {
  const light = themeBlock(css, '[data-ntasks].light');
  const dark = themeBlock(css, '[data-ntasks].dark');
  const missing = [...light.keys()].filter((name) => !dark.has(name));
  if (missing.length > 0) throw new Error(`${PACKAGE} sets ${missing.join(', ')} in light only.`);
  return { light, dark };
}

export function preciseStylesheet({ css, version }) {
  const { light, dark } = preciseTokens(css);
  const lines = (tokens) => [...tokens].map(([name, value]) => `  --precise-${name}: ${value};`).join('\n');
  return `/* Generated by \`pnpm generate\` (scripts/precise-tokens.mjs) from ${PACKAGE} ${version}'s
   stylesheet: Precise, Ntasks's design system, with the Notice blue. Edit the
   package, never this file. Dark is the default, as in notice.css. */
[data-theme="dark"],
:root {
${lines(dark)}
}
.light,
:root[data-theme="light"] {
${lines(light)}
}
`;
}

export function main(argv = process.argv.slice(2), root = REPO_ROOT) {
  const written = preciseStylesheet(installedStylesheet(root));
  const file = path.join(root, OUTPUT);
  if (argv.includes('--check')) {
    let current = '';
    try { current = readFileSync(file, 'utf8'); } catch { /* missing reads as stale */ }
    if (current === written) return 0;
    process.stderr.write(`${OUTPUT} is stale: run pnpm generate.\n`);
    return 1;
  }
  if (argv.includes('--write')) writeFileSync(file, written);
  else process.stdout.write(written);
  return 0;
}

if (invokedDirectly(process.argv[1], import.meta.url)) process.exitCode = main();
