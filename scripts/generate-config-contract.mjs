// Compile every checked TypeScript source that ships as a committed `.mjs` + `.d.mts` pair; `--check` fails when a pair is stale.
import { spawnSync } from 'node:child_process';
import { mkdtempSync, readFileSync, writeFileSync, rmSync } from 'node:fs';
import { tmpdir } from 'node:os';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

// Every checked TypeScript source that ships as a committed `.mjs` + `.d.mts`
// pair. The project decides what a source may reach: the
// portable one compiles with no ambient types, so a module the browser and the
// Workers import cannot quietly grow a `node:` import; the Node one adds
// @types/node for the terminal and local-runner adapters. Each project's
// `include` is the list of sources, so adding one is one line there.
const root = fileURLToPath(new URL('../', import.meta.url));
const PROJECTS = ['tsconfig.config-contract.json', 'tsconfig.config-contract.node.json'];
const check = process.argv.includes('--check');
const out = mkdtempSync(path.join(tmpdir(), 'config-contract-'));

/** The `.mts` sources one project owns, as extensionless repo-relative stems. */
function sourcesOf(project) {
  const { include } = JSON.parse(readFileSync(path.join(root, project), 'utf8'));
  return include.filter((file) => file.endsWith('.mts')).map((file) => file.slice(0, -'.mts'.length));
}

try {
  const stale = [];
  for (const [index, project] of PROJECTS.entries()) {
    const dir = path.join(out, String(index));
    const compiled = spawnSync(process.execPath, [
      path.join(root, 'packages/contract/node_modules/typescript/bin/tsc'),
      '-p', path.join(root, project), '--outDir', dir,
    ], { cwd: root, stdio: 'inherit' });
    if (compiled.error) throw compiled.error;
    if (compiled.status !== 0) {
      process.exitCode = compiled.status ?? 1;
      break;
    }
    for (const file of sourcesOf(project).flatMap((stem) => [`${stem}.mjs`, `${stem}.d.mts`])) {
      const generated = '// Generated by pnpm config:generate. Edit the sibling .mts source.\n' +
        readFileSync(path.join(dir, file), 'utf8');
      if (check) {
        let current;
        try { current = readFileSync(path.join(root, file), 'utf8'); }
        catch (error) { if (error.code !== 'ENOENT') throw error; }
        if (current !== generated) stale.push(file);
      } else writeFileSync(path.join(root, file), generated);
    }
  }
  if (stale.length) {
    process.stderr.write(`Stale configuration output; run pnpm config:generate:\n${stale.join('\n')}\n`);
    process.exitCode = 1;
  }
} finally { rmSync(out, { recursive: true, force: true }); }
